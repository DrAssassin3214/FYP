"""Builds ten ILLUSTRATIVE scenario case files from the built-in analysis example and runs each one.

Every number in these files is a placeholder (Source: Assumption, note ILLUSTRATIVE). They are NOT evidence and
NOT site data: they exist to show how the model's outputs move when its inputs move.
Run:  python examples/scenarios/make_scenarios.py        (writes the .json cases, summary.md, summary.csv, seed_variance.csv)
Open any .json file with Open in the GUI (Save/Open), or:  python -m app.cli analyze <file> --out out/
"""
import copy
import csv
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from app import service  # noqa: E402

OUT = Path(__file__).resolve().parent
NOTE = "ILLUSTRATIVE placeholder, not evidence"


def risk(c, rid):
    return next(r for r in c["risks"] if r["id"] == rid)


def setp(c, rid, p):
    risk(c, rid)["p"]["value"] = round(min(max(p, 0.01), 0.95), 3)


def scale_delay(c, rid, k):
    d = risk(c, rid)["delay"]
    for key in ("a", "m", "b"):
        d[key] = round(d[key] * k, 2)


def s01(c): return c
def s02(c):
    setp(c, "R-MAT", 0.8); risk(c, "R-MAT")["delay"]["b"] = 12; c["facts"]["material_stock_days"] = 0; return c
def s03(c):
    setp(c, "R-LAB", 0.7); setp(c, "R-SKILL", 0.5); c["facts"]["available_workers"] = 3; return c
def s04(c):
    setp(c, "R-WX", 0.6); d = risk(c, "R-WX")["delay"]; d["a"], d["m"], d["b"] = 2, 5, 10; return c
def s05(c):
    for r in c["risks"]: setp(c, r["id"], r["p"]["value"] * 0.4)
    return c
def s06(c):
    for r in c["risks"]: setp(c, r["id"], r["p"]["value"] * 1.5); scale_delay(c, r["id"], 1.5)
    return c
def s07(c):
    c["activity"]["deadline_days"]["value"] = 17; c["cost"]["ld_per_day_after_deadline"]["value"] = 20000; return c
def s08(c):
    c["cost"]["cost_per_delay_day"]["value"] = 800; c["cost"]["ld_per_day_after_deadline"]["value"] = 500; return c
def s09(c):
    for m in c["mitigations"]: m["cost"]["value"] = m["cost"]["value"] * 4
    return c
def s10(c):
    c["activity"]["deadline_days"]["value"] = 30; return c


SCENARIOS = [
    ("S01_baseline", "Baseline: the built-in ILLUSTRATIVE analysis example, unchanged.", s01),
    ("S02_material_crisis", "Brick supply crisis: R-MAT probability 0.8, longer worst-case delay, no stock on site.", s02),
    ("S03_labour_shortage", "Labour shortage: only 3 of 6 workers available; R-LAB 0.7, R-SKILL 0.5.", s03),
    ("S04_heavy_monsoon", "Heavy monsoon: R-WX probability 0.6 and delay 2 / 5 / 10 days.", s04),
    ("S05_well_managed_site", "Well-managed site: every risk probability scaled by 0.4.", s05),
    ("S06_everything_goes_wrong", "Everything goes wrong: every probability and every delay scaled by 1.5 (p capped at 0.95).", s06),
    ("S07_tight_deadline_high_penalty", "Tight deadline (17 days) with a high liquidated-damages rate (20,000 per day).", s07),
    ("S08_cheap_delay", "Delay is cheap: cost per delay day 800 and damages 500 per day.", s08),
    ("S09_expensive_responses", "Every candidate response costs four times as much as in the baseline.", s09),
    ("S10_relaxed_deadline", "Relaxed deadline (30 days): the planned duration is 16 days.", s10),
]


def build(name, desc, fn):
    c = fn(copy.deepcopy(service.example_analysis_case()))
    c["project"] = {**(c.get("project") or {}), "name": f"ILLUSTRATIVE scenario {name}",
                    "description": f"{desc} All numbers are placeholders, not evidence. Generated by examples/scenarios/make_scenarios.py."}
    return c


def main():
    rows, seedrows = [], []
    for name, desc, fn in SCENARIOS:
        case = build(name, desc, fn)
        (OUT / f"{name}.json").write_text(json.dumps(case, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        reg = service.run_case(case)
        ana = service.run_analysis(case)
        if not ana.get("ok", True) and "problems" in ana:
            raise SystemExit(f"{name}: {ana['problems']}")
        lv = reg["summary"]["levels"]
        s = ana["summary"]
        cmd = ana["command"]
        rows.append({
            "scenario": name, "description": desc,
            "High+Extreme": lv.get("High", 0) + lv.get("Extreme", 0), "Moderate": lv.get("Moderate", 0), "Low": lv.get("Low", 0),
            "mean_duration_d": round(s["mean"], 2), "p50_d": round(s["percentiles"]["P50"], 2), "p90_d": round(s["percentiles"]["P90"], 2),
            "p_any_delay": s["p_any_delay"], "p_exceed_deadline": s.get("p_exceed_deadline"),
            "command": cmd.get("command"), "preferred_option": cmd.get("selected_option_id"),
        })
    base = service.example_analysis_case()
    for sd in (1, 2, 3, 4, 5, 12345):
        c = copy.deepcopy(base); c["simulation"]["seed"] = sd
        a = service.run_analysis(c); s = a["summary"]
        seedrows.append({"seed": sd, "mean_duration_d": round(s["mean"], 2), "p50_d": round(s["percentiles"]["P50"], 2), "p90_d": round(s["percentiles"]["P90"], 2),
                         "p_exceed_deadline": s.get("p_exceed_deadline"), "command": a["command"].get("command"), "preferred_option": a["command"].get("selected_option_id")})
    for fname, data in (("summary.csv", rows), ("seed_variance.csv", seedrows)):
        with open(OUT / fname, "w", newline="", encoding="utf-8-sig") as f:
            w = csv.DictWriter(f, fieldnames=list(data[0])); w.writeheader(); w.writerows(data)
    md = ["# Scenario files (all ILLUSTRATIVE)", "",
          "Ten case files built from the built-in analysis example. Every number is a placeholder (Source: Assumption), not evidence and not site data; "
          "they show how the model's outputs move when inputs move. Open a file with **Open** in the GUI, or run `python -m app.cli analyze <file> --out out/`.", "",
          "| Scenario | What changes | High+Extreme / Moderate / Low | Mean, P50, P90 duration (d) | P(finish after deadline) | Command | Preferred option |", "|---|---|---|---|---|---|---|"]
    for r in rows:
        md.append(f"| {r['scenario']} | {r['description']} | {r['High+Extreme']} / {r['Moderate']} / {r['Low']} | {r['mean_duration_d']}, {r['p50_d']}, {r['p90_d']} | {r['p_exceed_deadline']} | {r['command']} | {r['preferred_option']} |")
    md += ["", "## Same case, different random seeds (simulation noise only)", "",
           "| Seed | Mean (d) | P50 (d) | P90 (d) | P(after deadline) | Command | Preferred option |", "|---|---|---|---|---|---|---|"]
    for r in seedrows:
        md.append(f"| {r['seed']} | {r['mean_duration_d']} | {r['p50_d']} | {r['p90_d']} | {r['p_exceed_deadline']} | {r['command']} | {r['preferred_option']} |")
    md += ["", "Source of every number in the tables: Derived Calculation from the ILLUSTRATIVE inputs in the case files (10,000 simulated runs per case, seed 12345 unless stated).", ""]
    (OUT / "README.md").write_text("\n".join(md), encoding="utf-8")
    print("\n".join(md))


if __name__ == "__main__":
    main()
